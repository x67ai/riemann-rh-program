#!/usr/bin/env python3
"""gen_prove2me_layout.py -- emit the Prove2Me-layout mirror of the WeilContainment topics (Session 30, D5 unit).
usage: gen_prove2me_layout.py <rh-program/lean/comparator> <prove2me_workspace>
Reads the TRUSTED files (ChallengeDeps/WeilContainment.lean, Challenge/WeilContainment.lean, Challenge/WeilContainmentOne.lean),
strips the comparator headers, and writes
  Definitions/Def_WeilContainment.lean                    the vocabulary, verbatim (import Mathlib, namespace WeilContainment)
  Theorems/Thm_WeilContainment_<suffix>.lean              one file per challenge theorem, statement text VERBATIM from the
                                                          challenge (from the first binder to `:= by`), renamed to the
                                                          platform's dotted form `WeilContainment.<suffix>` so that the platform's
                                                          module slug Thm_<theorem_name with dots as underscores> is the file name;
                                                          ends `by sorry` as the platform stores stubs.
The rename `weilContainment_<suffix>` -> `WeilContainment.<suffix>` is the ONLY change; the file records the comparator name.
Nothing is uploaded; nothing here talks to the network."""
import os, re, sys

comp, ws = sys.argv[1], sys.argv[2]

def strip_header_comments(src):
    # drop the leading block comments (copyright + module comment); keep from the first `import`
    i = src.find("\nimport ")
    return src[i + 1:] if i >= 0 else src

deps = strip_header_comments(open(os.path.join(comp, "ChallengeDeps", "WeilContainment.lean"), encoding="utf-8").read())
os.makedirs(os.path.join(ws, "Definitions"), exist_ok=True)
os.makedirs(os.path.join(ws, "Theorems"), exist_ok=True)
with open(os.path.join(ws, "Definitions", "Def_WeilContainment.lean"), "w", encoding="utf-8") as f:
    f.write("-- Def_WeilContainment: the trusted vocabulary of the D5 unit (barrier-zoo IV.1), VERBATIM from\n"
            "-- rh-program/lean/comparator/ChallengeDeps/WeilContainment.lean (comparator headers stripped). Mathlib only.\n"
            "-- Generated by results/d5-lean-s30/tools/gen_prove2me_layout.py; not uploaded anywhere.\n")
    f.write(deps)

rx = re.compile(r"^/--(.*?)-/\s*^theorem\s+weilContainment_([A-Za-z0-9_']+)\s*(.*?):=\s*by\s*\n\s*sorry", re.S | re.M)
count = 0
for chal in ("WeilContainmentOne.lean", "WeilContainment.lean"):
    src = open(os.path.join(comp, "Challenge", chal), encoding="utf-8").read()
    for m in rx.finditer(src):
        doc, suffix, stmt = m.group(1), m.group(2), m.group(3)
        # normalize the statement's leading whitespace exactly as in the challenge (keep verbatim)
        out = ("-- Thm_WeilContainment_%s: platform stub of the challenge theorem `weilContainment_%s` of\n"
               "-- rh-program/lean/comparator/Challenge/%s (statement VERBATIM; the name is the platform's dotted form,\n"
               "-- module slug = Thm_<theorem_name with dots as underscores>). Ends `by sorry` as the platform stores stubs.\n"
               "-- Generated by results/d5-lean-s30/tools/gen_prove2me_layout.py; not uploaded anywhere.\n"
               "import Definitions.Def_WeilContainment\nimport Mathlib\n\nnoncomputable section\n\nopen WeilContainment\n\n"
               "/--%s-/\ntheorem WeilContainment.%s %s:= by sorry\n") % (suffix, suffix, chal, doc, suffix, stmt)
        with open(os.path.join(ws, "Theorems", "Thm_WeilContainment_%s.lean" % suffix), "w", encoding="utf-8") as f:
            f.write(out)
        count += 1
        print("wrote Theorems/Thm_WeilContainment_%s.lean (from %s)" % (suffix, chal))
print("theorem stubs written:", count)
