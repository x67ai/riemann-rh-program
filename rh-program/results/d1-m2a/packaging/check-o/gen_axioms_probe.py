#!/usr/bin/env python3
"""CHECK-O step 2: build Job 2's OWN #print axioms probe (does not reuse
comparator/PrintAxioms/DBN.lean or packaging/print-axioms-bridge.lean).

Enumerates every top-level theorem/lemma of Zeta23/DBN/*.lean, of comparator/Solution/DBN.lean
and every name of comparator/Challenge/DBN.lean, tracking namespaces, and emits one
`#print axioms <fully qualified name>` per declaration, plus a `#check @` for the seven
challenge names.
Usage: gen_axioms_probe.py <lean-tree> <out.lean>
"""
import os, re, sys

TREE, OUT = sys.argv[1], sys.argv[2]

def strip_c(s):
    out, i, depth, n = [], 0, 0, len(s)
    while i < n:
        if s.startswith("/-", i): depth += 1; out.append("  "); i += 2; continue
        if s.startswith("-/", i) and depth: depth -= 1; out.append("  "); i += 2; continue
        if depth: out.append("\n" if s[i] == "\n" else " "); i += 1; continue
        if s.startswith("--", i):
            j = s.find("\n", i); j = n if j < 0 else j
            out.append(" " * (j - i)); i = j; continue
        out.append(s[i]); i += 1
    return "".join(out)

DECL = re.compile(r"^(?:@\[[^\]]*\]\s*)?(?:private\s+|protected\s+|noncomputable\s+)*"
                  r"(theorem|lemma)\s+([A-Za-z_][A-Za-z0-9_'.!?]*)")

def names(rel):
    code = strip_c(open(os.path.join(TREE, rel), encoding="utf-8").read())
    ns, out = [], []
    for line in code.split("\n"):
        m = re.match(r"^namespace\s+(\S+)", line)
        if m: ns.append(m.group(1)); continue
        m = re.match(r"^end\s+(\S+)\s*$", line)
        if m and ns and ns[-1] == m.group(1): ns.pop(); continue
        m = DECL.match(line)
        if m:
            out.append((".".join(ns + [m.group(2)]) if ns else m.group(2), rel))
    return out

groups = []
dbn = os.path.join(TREE, "Zeta23/DBN")
for f in sorted(os.listdir(dbn)):
    if f.endswith(".lean"):
        groups.append(("Zeta23/DBN/" + f, names("Zeta23/DBN/" + f)))
groups.append(("comparator/Solution/DBN.lean", names("comparator/Solution/DBN.lean")))
chal = names("comparator/Challenge/DBN.lean")

with open(OUT, "w", encoding="utf-8") as fh:
    fh.write("-- CHECK-O step 2: Job 2's own #print axioms probe (generated by check-o/gen_axioms_probe.py).\n")
    fh.write("-- Not derived from comparator/PrintAxioms/DBN.lean or packaging/print-axioms-bridge.lean.\n")
    fh.write("import Solution.DBN\n\n")
    total = 0
    for title, ns in groups:
        fh.write('-- ===== %s (%d) =====\n' % (title, len(ns)))
        for n, _ in ns:
            fh.write("#print axioms %s\n" % n); total += 1
        fh.write("\n")
    fh.write('-- ===== Challenge/DBN.lean names, as proved in Solution.DBN (%d) =====\n' % len(chal))
    for n, _ in chal:
        fh.write("#print axioms %s\n" % n); total += 1
    fh.write("\n-- ===== elaborated types of the seven challenge statements =====\n")
    for n, _ in chal:
        fh.write("#check @%s\n" % n)
print("probe written: %s" % OUT)
for title, ns in groups:
    print("  %-40s %d theorems" % (title, len(ns)))
print("  %-40s %d names" % ("comparator/Challenge/DBN.lean", len(chal)))
print("  total #print axioms lines: %d" % (total,))
