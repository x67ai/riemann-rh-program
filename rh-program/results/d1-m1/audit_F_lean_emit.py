"""audit_F_lean_emit.py -- AUDIT F: JSON transcript -> Lean `W1Data` literal emitter, and a
scratch Lean module asserting `checkW1 <literal> = true` (or `= false` for corrupted
files) by `decide +kernel`.

This is the producer-side, UNTRUSTED translation FORMAT.md sec. 7 / sec. 10 describes
("the JSON->Lean literal emitter is producer-side and untrusted; the kernel re-checks
everything that matters from the literals").  Session 8 never ran the Lean checker on a
real producer transcript (Examples.lean holds only the artificial sec. 11 data); this
script closes that gap for the audit.

Usage:
  python3 audit_F_lean_emit.py OUT.lean [--expect true|false] FILE.json [FILE2.json ...]
The emitted module imports Zeta23.W1.Checker and, for each file, defines
`auditF_<i> : W1Data` and `theorem auditF_<i>_check : checkW1 auditF_<i> = <expect> :=
by decide +kernel`; when the file carries a modulus_floor, also the checkW1Floor theorem
(expected true only for uncorrupted files).
"""
import json
import os
import sys


def lit_pair(r):
    return "(%s, %s)" % (r["n"], r["d"])


def emit_data(name, doc):
    rect, sc, mesh = doc["rect"], doc["scales"], doc["mesh"]
    rows = ",\n    ".join("⟨%s, %s, %s, %s, %s, %s⟩" % (r["reLo"], r["reHi"], r["imLo"], r["imHi"], r["argLo"], r["argHi"])
                          for r in doc["segments"])
    s = ["def %s : W1Data where" % name,
         "  p1 := %s;  q1 := %s" % (rect["sigma1"]["n"], rect["sigma1"]["d"]),
         "  p2 := %s;  q2 := %s" % (rect["sigma2"]["n"], rect["sigma2"]["d"]),
         "  a1 := %s;  b1 := %s" % (rect["T1"]["n"], rect["T1"]["d"]),
         "  a2 := %s;  b2 := %s" % (rect["T2"]["n"], rect["T2"]["d"]),
         "  K := %s" % sc["K"],
         "  A := %s" % sc["A"],
         "  m := %s" % doc["claimed_m"]]
    for e in ("bottom", "right", "top", "left"):
        s.append("  %s := [%s]" % (e, ", ".join(lit_pair(r) for r in mesh[e])))
    s.append("  rows := [\n    %s]" % rows)
    return "\n".join(s)


def main(argv):
    out = argv[0]
    expect = "true"
    files = []
    i = 1
    while i < len(argv):
        if argv[i] == "--expect":
            expect = argv[i + 1]
            i += 2
        else:
            files.append(argv[i])
            i += 1
    parts = ["import Zeta23.W1.Checker", "", "namespace Zeta23", "namespace W1", "",
             "-- AUDIT F scratch module: producer transcripts as W1Data literals (untrusted emitter),",
             "-- checked by decide +kernel.  Generated by audit_F_lean_emit.py; not part of the library.", ""]
    for k, path in enumerate(files):
        with open(path) as fh:
            doc = json.load(fh)
        name = "auditF_%d" % k
        parts.append("/-- %s (%s/%s, m = %s, %d rows) -/" % (os.path.basename(path), doc["function"], doc["mode"], doc["claimed_m"], len(doc["segments"])))
        parts.append(emit_data(name, doc))
        parts.append("")
        parts.append("theorem %s_check : checkW1 %s = %s := by decide +kernel" % (name, name, expect))
        if "modulus_floor" in doc and expect == "true":
            fl = doc["modulus_floor"]
            parts.append("def %s_floor : W1Floor where\n  Fn := %s\n  Fd := %s" % (name, fl["Fn"], fl["Fd"]))
            parts.append("theorem %s_floor_check : checkW1Floor %s %s_floor = true := by decide +kernel" % (name, name, name))
        parts.append("")
    parts += ["end W1", "end Zeta23", ""]
    with open(out, "w") as fh:
        fh.write("\n".join(parts))
    print("wrote %s (%d transcripts, expect %s)" % (out, len(files), expect))


if __name__ == "__main__":
    main(sys.argv[1:])
