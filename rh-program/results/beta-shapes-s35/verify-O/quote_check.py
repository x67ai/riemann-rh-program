def norm(s):
    s = s.replace('’',"'").replace('‘',"'").replace('“','"').replace('”','"')
    s = s.replace('ﬁ','fi').replace('ﬂ','fl').replace('ﬀ','ff')
    s = re.sub(r'-\s*\n\s*', '', s)  # dehyphenate
    return re.sub(r'\s+', ' ', s)
def find(path, needle):
    t = open(path, encoding='utf-8', errors='replace').read()
    pages = t.split('\f')
    hits = []
    for i, p in enumerate(pages):
        if norm(needle).lower() in norm(p).lower():
            hits.append(i+1)
    if not hits:  # try across page boundary
        if norm(needle).lower() in norm(t.replace('\f',' ')).lower(): hits=['cross-page']
    return hits
